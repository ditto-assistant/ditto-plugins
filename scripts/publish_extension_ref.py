#!/usr/bin/env python3
"""Publish one plugin folder as the root of a dedicated branch for Gemini CLI.

Gemini CLI installs a GitHub repository only from its root: the manifest must
be `gemini-extension.json` at the top of the checkout, and skills load only from
`<root>/skills/`. It accepts `--ref` but no subdirectory. A root manifest here
would also make `agy plugin install <repo>` treat the whole repository as a
Gemini extension instead of installing plugins/ditto.

This script commits the tree of `<source>:plugins/<plugin>` unchanged as the
next commit of the `gemini-extension` branch, so

    gemini extensions install https://github.com/ditto-assistant/ditto-plugins --ref gemini-extension

installs plugins/ditto with its manifest, skills and MCP server. Each publish
fast-forwards the branch from its previous head. It never force-pushes and does
nothing when the tree is unchanged.
"""
import argparse
import subprocess
import sys

MANIFEST = "gemini-extension.json"


def git(*args, check=True):
    result = subprocess.run(["git", *args], capture_output=True, text=True)
    if check and result.returncode:
        raise RuntimeError(f"git {' '.join(args)} failed: {result.stderr.strip()}")
    return result


def publish(source, prefix, branch, remote, dry_run=False):
    commit = git("rev-parse", "--verify", f"{source}^{{commit}}").stdout.strip()
    tree = git("rev-parse", "--verify", f"{commit}:{prefix}").stdout.strip()
    if git("cat-file", "-e", f"{commit}:{prefix}/{MANIFEST}", check=False).returncode:
        raise ValueError(f"{prefix}/{MANIFEST} is missing at {commit}")
    tracking = f"refs/remotes/{remote}/{branch}"
    fetched = git("fetch", "--no-tags", remote, f"+refs/heads/{branch}:{tracking}", check=False)
    if fetched.returncode and git("ls-remote", "--exit-code", "--heads", remote, branch, check=False).returncode != 2:
        raise RuntimeError(f"could not fetch {branch}: {fetched.stderr.strip()}")
    parent = git("rev-parse", "--verify", "--quiet", tracking, check=False).stdout.strip() if not fetched.returncode else ""
    if parent and git("rev-parse", f"{parent}^{{tree}}").stdout.strip() == tree:
        print(f"{branch}: already {prefix} from {commit[:12]} (tree {tree[:12]}); nothing to publish")
        return None
    message = f"{prefix} from {commit}\n\nGenerated by scripts/publish_extension_ref.py; do not edit this branch.\n"
    new = git("commit-tree", tree, *(["-p", parent] if parent else []), "-m", message).stdout.strip()
    if dry_run:
        print(f"{branch}: dry run; would push {new[:12]} ({prefix} at {commit[:12]}) on top of {parent[:12] or 'nothing'}")
        return new
    git("push", remote, f"{new}:refs/heads/{branch}")
    print(f"{branch}: published {new} ({prefix} at {commit})")
    return new


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", default="HEAD", help="commit to publish from (default HEAD)")
    parser.add_argument("--plugin", default="ditto")
    parser.add_argument("--branch", default="gemini-extension")
    parser.add_argument("--remote", default="origin")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    try:
        publish(args.source, f"plugins/{args.plugin}", args.branch, args.remote, args.dry_run)
    except (RuntimeError, ValueError) as error:
        sys.exit(str(error))


if __name__ == "__main__":
    main()
